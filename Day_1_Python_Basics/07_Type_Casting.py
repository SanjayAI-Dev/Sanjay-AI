# 07_Type_Casting
# its a function where we can convert values from one data type to another data type

a=10
print(a)

print(type(a))
# here we change integer to float data type
a=float(10)
print(a)
print(type(a))

# now we change integer to character of string

a=str(10)
print(a)
print(type(a))


#now we change from float to integer
b=20.556
print(b)
print(type(b))

b = int(20.556)
print(b)
